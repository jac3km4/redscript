use std::fmt;

/// Failures in REDmod capability validation and resolved semantic checks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SemanticError {
    UnsupportedType,
    NativeReferenceLocal,
    NativeReferenceReturn,
    NestedNativeReference,
    UnsupportedFunctionType,
    UnsupportedGenericFunction,
    DuplicateBinding,
    UnsupportedExpressionBody,
    PersistentRequiresAggregateField,
    EventRequiresClassOrMethodTarget,
    EventVisibility,
    EventQualifiers,
    EventReturnType,
    UnsupportedAnnotation,
    AnnotatedMemberVisibility,
    InvalidRuntimeProperty,
    InvalidHint,
    InvalidConditionAnnotation,
    DuplicateConditionAnnotation,
    UnsupportedGenericType,
    MissingLocalType,
    UnsupportedPatternBinding,
    UnsupportedForIn,
    UnsupportedCommunityExpression,
    UnsupportedEmptyArrayLiteral,
    UnsupportedGenericCall,
    InvalidCastTypeArguments,
    EventOverride,
    IncompatibleBaseCallback,
    MissingOverride,
    OverrideParameterFlagsMismatch,
    OverrideFinalMethod,
    OverrideReturnTypeMismatch,
    OverrideWithoutBase,
    ExtendImportOnlyTarget,
    UnsupportedCallbackPatchReturn,
    PatchModDefinedClass,
    PersistentFieldAccess,
}

impl fmt::Display for SemanticError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::UnsupportedType => "this reference or generic type is not supported",
            Self::NativeReferenceLocal => "local variables cannot use ref<T>",
            Self::NativeReferenceReturn => "functions cannot return ref<T>",
            Self::NestedNativeReference => "ref<T> cannot be nested inside another reference or array",
            Self::UnsupportedFunctionType => "function types are not supported",
            Self::UnsupportedGenericFunction => "custom generic functions are not supported",
            Self::DuplicateBinding => "this name is already used in the function; rename the parameter or local, even in nested blocks",
            Self::UnsupportedExpressionBody => "expression-bodied functions are not supported; use a block body with an explicit return for a result",
            Self::PersistentRequiresAggregateField => "persistent requires a class or struct field",
            Self::EventRequiresClassOrMethodTarget => "declare the event inside a class or use a method patch annotation",
            Self::EventVisibility => "events must omit visibility or be protected",
            Self::EventQualifiers => "events cannot be static, final or const",
            Self::EventReturnType => "events cannot declare a return type",
            Self::UnsupportedAnnotation => "unsupported annotation or arguments; check the annotation's spelling, declaration and arguments",
            Self::AnnotatedMemberVisibility => "annotated members must omit public, protected and private",
            Self::InvalidHint => "use @hint(\"text\") on a field",
            Self::InvalidRuntimeProperty => "use @runtimeProperty(\"name\", \"value\") on a field",
            Self::InvalidConditionAnnotation => "use @if(ModuleExists(\"module\")) or @if(!ModuleExists(\"module\")) on a function or method",
            Self::DuplicateConditionAnnotation => "a declaration may have only one if annotation",
            Self::UnsupportedGenericType => "custom generic types are not supported",
            Self::MissingLocalType => "local variables need an explicit type; write var name: Type = value;",
            Self::UnsupportedPatternBinding => "pattern bindings are not supported",
            Self::UnsupportedForIn => "for-in loops are not supported; use for (initialization; condition; update) { ... }",
            Self::UnsupportedCommunityExpression => "lambdas and interpolated strings are not supported",
            Self::UnsupportedEmptyArrayLiteral => "empty array literals are not supported",
            Self::UnsupportedGenericCall => "custom generic calls are not supported",
            Self::InvalidCastTypeArguments => "Cast needs one target type; write Cast<TargetType>(value)",
            Self::EventOverride => "events do not use override",
            Self::IncompatibleBaseCallback => "the inherited callback must return Bool to match an event; check the base declaration",
            Self::MissingOverride => "this method matches an inherited method; add override if replacement is intended",
            Self::OverrideParameterFlagsMismatch => "match each parameter's out modifier to the inherited method",
            Self::OverrideFinalMethod => "the inherited method is final and cannot be overridden",
            Self::OverrideReturnTypeMismatch => "this override must return the same type as the inherited method",
            Self::OverrideWithoutBase => "no inherited method matches this override; check its name and parameter types",
            Self::ExtendImportOnlyTarget => "cannot extend an importonly target",
            Self::UnsupportedCallbackPatchReturn => "only callbacks returning Bool can be patched as events",
            Self::PatchModDefinedClass => "patches on mod-defined classes are unsafe; check the annotation's target class",
            Self::PersistentFieldAccess => "this persistent field is accessible only in its declaring class or subclasses; use an accessor method",
        })
    }
}
