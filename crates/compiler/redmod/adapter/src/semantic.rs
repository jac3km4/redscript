use std::fmt;

/// Failures in REDmod capability validation and resolved semantic checks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SemanticError {
    UnsupportedType,
    UnsupportedFunctionType,
    UnsupportedGenericFunction,
    DuplicateBinding,
    UnsupportedExpressionBody,
    PersistentRequiresAggregateField,
    EventRequiresClassOrMethodTarget,
    EventVisibility,
    EventQualifiers,
    EventReturnType,
    UnsupportedAnnotation,
    AnnotatedMemberVisibility,
    InvalidRuntimeProperty,
    InvalidHint,
    InvalidConditionAnnotation,
    DuplicateConditionAnnotation,
    UnsupportedGenericType,
    MissingLocalType,
    UnsupportedPatternBinding,
    UnsupportedForIn,
    UnsupportedCommunityExpression,
    UnsupportedEmptyArrayLiteral,
    UnsupportedGenericCall,
    InvalidCastTypeArguments,
    EventOverride,
    IncompatibleBaseCallback,
    MissingOverride,
    OverrideParameterFlagsMismatch,
    OverrideFinalMethod,
    OverrideReturnTypeMismatch,
    OverrideWithoutBase,
    ExtendImportOnlyTarget,
    UnsupportedCallbackPatchReturn,
    PatchModDefinedClass,
    PersistentFieldAccess,
}

impl fmt::Display for SemanticError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::UnsupportedType => "unsupported REDmod reference or generic type",
            Self::UnsupportedFunctionType => "function types are not supported",
            Self::UnsupportedGenericFunction => "custom generic functions are not supported",
            Self::DuplicateBinding => "duplicate function-wide binding",
            Self::UnsupportedExpressionBody => "expression-bodied functions are not supported",
            Self::PersistentRequiresAggregateField => "persistent requires a class or struct field",
            Self::EventRequiresClassOrMethodTarget => "events require a class or method annotation target",
            Self::EventVisibility => "events must omit visibility or be protected",
            Self::EventQualifiers => "events cannot be static, final or const",
            Self::EventReturnType => "events cannot declare a return type",
            Self::UnsupportedAnnotation => "annotation semantics are not supported by the REDmod adapter",
            Self::AnnotatedMemberVisibility => "annotated members must omit visibility",
            Self::InvalidHint => "hint requires a field and one string literal",
            Self::InvalidRuntimeProperty => "runtimeProperty requires a field and two string literals",
            Self::InvalidConditionAnnotation => "if requires one module condition on a function or method",
            Self::DuplicateConditionAnnotation => "a declaration may have only one if annotation",
            Self::UnsupportedGenericType => "custom generic types are not supported",
            Self::MissingLocalType => "REDmod locals require an explicit type",
            Self::UnsupportedPatternBinding => "pattern bindings are not supported",
            Self::UnsupportedForIn => "for-in is not supported",
            Self::UnsupportedCommunityExpression => "community expression is not supported",
            Self::UnsupportedEmptyArrayLiteral => "empty array literals are not supported",
            Self::UnsupportedGenericCall => "custom generic calls are not supported",
            Self::InvalidCastTypeArguments => "Cast requires one explicit target type",
            Self::EventOverride => "events do not use override",
            Self::IncompatibleBaseCallback => "base callback has a non-Void return; REDmod event compatibility is unsupported",
            Self::MissingOverride => "overriding a resolved base signature requires override",
            Self::OverrideParameterFlagsMismatch => "override parameter out flags differ from the base signature",
            Self::OverrideFinalMethod => "cannot override a final method",
            Self::OverrideReturnTypeMismatch => "override return type differs from the base signature",
            Self::OverrideWithoutBase => "override has no matching base signature",
            Self::ExtendImportOnlyTarget => "cannot extend an importonly target",
            Self::UnsupportedCallbackPatchReturn => "non-Void callback patches require target return adaptation which is unsupported",
            Self::PatchModDefinedClass => "patches on mod-defined classes are unsafe in REDmod",
            Self::PersistentFieldAccess => "persistent fields of mod-defined classes are accessible only inside the declaring class; use an accessor",
        })
    }
}
